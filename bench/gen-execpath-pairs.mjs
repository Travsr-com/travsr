#!/usr/bin/env node
// Ground-truth (source, sink) pair generator for get_execution_path benchmarking.
//
// Derives pairs directly from the indexed graph rather than hand-labelling them:
// a pair is admitted only when a real `ref/call` path of a known hop distance
// exists between two *uniquely-named* function/method nodes. That gives every
// pair a ground truth the harness can score against — the shortest-path length
// is known before the tool is ever called.
//
// Why uniquely-named: `get_execution_path` resolves its arguments by signature.
// `fn:main` matches 15 nodes in travsr's own graph, so a pair using it would
// measure signature disambiguation rather than path retrieval. Ambiguous
// signatures are excluded so the benchmark isolates one variable.
//
// Deterministic: sorts candidates and walks them in order, no RNG, so re-running
// on an unchanged graph reproduces the same set.
//
// Usage:
//   node bench/gen-execpath-pairs.mjs [--db path/to/graph.db] [--label travsr]
//                                     [--per-hop 12] [--out bench/queries-execpath-<label>.json]
//
// Requires: sqlite3 CLI on PATH (same dependency-free approach as run.mjs, which
// shells out to the travsr binary rather than linking a driver).

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const LABEL = arg("label", "travsr");
const DB = arg("db", join(ROOT, ".travsr/graph.db"));
const PER_HOP = parseInt(arg("per-hop", "12"), 10);
const OUT = arg("out", join(HERE, `queries-execpath-${LABEL}.json`));
const HOPS = [2, 3, 4];

function q(sql) {
  const out = execFileSync("sqlite3", [DB, "-separator", "\t", sql], {
    encoding: "utf8",
    maxBuffer: 512 * 1024 * 1024,
  });
  return out.split("\n").filter(Boolean).map((l) => l.split("\t"));
}

// ── unique fn/method signatures only ─────────────────────────────────────────
const idSig = new Map();
for (const [id, sig] of q(
  `SELECT id, signature FROM nodes
    WHERE kind IN ('function','method')
      AND signature IN (
        SELECT signature FROM nodes
         WHERE kind IN ('function','method')
         GROUP BY signature HAVING COUNT(*) = 1
      )`
)) {
  idSig.set(id, sig);
}

// ── ref/call adjacency restricted to those nodes ─────────────────────────────
const adj = new Map();
let edgeCount = 0;
for (const [src, dst] of q(`SELECT src, dst FROM edges WHERE kind = 'ref/call'`)) {
  if (!idSig.has(src) || !idSig.has(dst)) continue;
  if (!adj.has(src)) adj.set(src, []);
  adj.get(src).push(dst);
  edgeCount++;
}
for (const v of adj.values()) v.sort();

// ── BFS: first time we reach a node IS its shortest hop distance ─────────────
function reachable(src, maxDepth) {
  const dist = new Map([[src, 0]]);
  const byDepth = new Map();
  let frontier = [src];
  for (let d = 1; d <= maxDepth; d++) {
    const next = [];
    for (const n of frontier) {
      for (const m of adj.get(n) ?? []) {
        if (dist.has(m)) continue;
        dist.set(m, d);
        next.push(m);
        if (!byDepth.has(d)) byDepth.set(d, []);
        byDepth.get(d).push(m);
      }
    }
    frontier = next;
    if (!frontier.length) break;
  }
  return byDepth;
}

const sources = [...adj.keys()].sort();
const picked = new Map(HOPS.map((h) => [h, []]));
const usedSink = new Set();

for (const src of sources) {
  if (HOPS.every((h) => picked.get(h).length >= PER_HOP)) break;
  const byDepth = reachable(src, Math.max(...HOPS));
  for (const hop of HOPS) {
    if (picked.get(hop).length >= PER_HOP) continue;
    const cand = (byDepth.get(hop) ?? []).find((d) => !usedSink.has(d));
    if (cand === undefined) continue;
    usedSink.add(cand);
    picked.get(hop).push({
      id: `H${hop}-${String(picked.get(hop).length + 1).padStart(2, "0")}`,
      hops: hop,
      source: idSig.get(src),
      sink: idSig.get(cand),
    });
  }
}

const pairs = HOPS.flatMap((h) => picked.get(h));
const doc = {
  _comment:
    "Ground-truth (source, sink) pairs for get_execution_path. Generated by " +
    "bench/gen-execpath-pairs.mjs from the indexed graph — a pair exists only " +
    "when a real ref/call path of `hops` length connects two uniquely-named " +
    "function/method nodes. `hops` is the true shortest-path length, so a " +
    "harness can score both recall (was the sink returned?) and precision " +
    "(how much of the result is path vs padding). Regenerate after a reindex; " +
    "signatures are graph-specific.",
  _generated_from: { label: LABEL, db: DB, per_hop: PER_HOP },
  _graph: { unique_fn_nodes: idSig.size, ref_call_edges_between_them: edgeCount },
  pairs,
};

writeFileSync(OUT, JSON.stringify(doc, null, 2) + "\n");
console.log(`graph: ${idSig.size} unique fn/method nodes, ${edgeCount} ref/call edges between them`);
for (const h of HOPS) console.log(`  ${h}-hop pairs: ${picked.get(h).length}`);
console.log(`wrote ${pairs.length} pairs → ${OUT}`);
